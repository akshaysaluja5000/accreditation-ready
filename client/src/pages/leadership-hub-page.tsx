function getEffectiveRole(user: { isAdmin: boolean; leadershipRole?: string | null }) {
  const lr = (user.leadershipRole as string) || "learner";
  if (user.isAdmin && (LEADERSHIP_RANK[lr] ?? 0) < LEADERSHIP_RANK["admin"]) return "admin";
  return lr;
}

